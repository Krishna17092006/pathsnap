"""Data decision (KKR): should the two noisy-label train trips be dropped from training?

Trips 00000002 and 00000033 are flagged in results/candidates/dataset_summary.md: more than 5% of
their fast fixes move against their labelled arc (GPS jitter, and a reference route that covers
only part of the drive). Keeping them adds noisy labels; dropping them loses training data.

Design (no leakage, like-for-like comparison):
  - the same 5 GroupKFold folds as every model (src/evaluate.group_folds)
  - in each fold the model is trained twice: on all training-fold trips, and on the training-fold
    trips minus the noisy ones
  - both versions are scored on the SAME validation trips with the same metrics
  - the decision uses the CV means; student_test is reported for information only
Models: gaussian_nb (KKR) and logreg (Krishna Jha's registry entry, used as registered).

Run from the project root (after build_dataset and features):
    python -m src.label_noise_experiment

Writes results/candidates/label_noise_experiment.csv and label_noise_experiment.md
"""
from __future__ import annotations

import time

import pandas as pd

from .config import PROCESSED_DIR, RESULTS_DIR, SEED
from .evaluate import evaluate_predictions, fit_predict, group_folds
from .features import FEATURE_COLUMNS, load_or_build
from .model_zoo import get_spec

NOISY_TRIPS = ["00000002", "00000033"]
MODELS = ["gaussian_nb", "logreg"]
METRICS = ["top1", "macro_f1", "log_loss", "route_continuity"]
OUT_DIR = RESULTS_DIR / "candidates"


def _run(spec, train_rows, eval_rows, eval_fixes) -> dict:
    _, prob, fit_s, _ = fit_predict(spec.factory, spec.params, train_rows, eval_rows, FEATURE_COLUMNS,
                                    spec.max_train_rows, SEED)
    m = evaluate_predictions(eval_rows, prob, eval_fixes)
    return {k: m[k] for k in METRICS} | {"fit_s": round(fit_s, 1)}


def main(argv=None) -> None:
    t0 = time.time()
    train = load_or_build("train")
    test = load_or_build("student_test")
    fixes_train = pd.read_parquet(PROCESSED_DIR / "fixes_train.parquet")
    fixes_test = pd.read_parquet(PROCESSED_DIR / "fixes_student_test.parquet")
    noisy = set(NOISY_TRIPS)
    rows = []
    for name in MODELS:
        spec = get_spec(name)
        for fold, tr_ids, va_ids in group_folds(train):
            tr = train[train["trip_id"].isin(tr_ids)]
            va = train[train["trip_id"].isin(va_ids)]
            va_fix = fixes_train[fixes_train["trip_id"].isin(va_ids)]
            for variant, rows_used in (("all_trips", tr), ("without_noisy", tr[~tr["trip_id"].isin(noisy)])):
                rec = {"model": name, "split": f"cv_fold_{fold}", "variant": variant,
                       "train_trips": rows_used["trip_id"].nunique(),
                       "noisy_trips_in_training": len(noisy & set(rows_used["trip_id"])),
                       "noisy_trips_in_validation": len(noisy & set(va_ids))}
                rec.update(_run(spec, rows_used, va, va_fix))
                rows.append(rec)
                print(f"[{name} fold {fold} {variant:>13}] Top-1 {rec['top1']:.4f}  macro F1 {rec['macro_f1']:.4f}  "
                      f"log loss {rec['log_loss']:.4f}", flush=True)
        for variant, rows_used in (("all_trips", train), ("without_noisy", train[~train["trip_id"].isin(noisy)])):
            rec = {"model": name, "split": "student_test", "variant": variant,
                   "train_trips": rows_used["trip_id"].nunique(),
                   "noisy_trips_in_training": len(noisy & set(rows_used["trip_id"])), "noisy_trips_in_validation": 0}
            rec.update(_run(spec, rows_used, test, fixes_test))
            rows.append(rec)
            print(f"[{name} student_test {variant:>13}] Top-1 {rec['top1']:.4f}", flush=True)

    df = pd.DataFrame(rows)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    df.to_csv(OUT_DIR / "label_noise_experiment.csv", index=False)

    cv = df[df["split"].str.startswith("cv_")]
    mean = cv.groupby(["model", "variant"])[METRICS].mean().unstack("variant")
    # folds where the noisy trips were actually in training (elsewhere both variants are identical)
    affected = cv[cv["noisy_trips_in_training"].groupby([cv["model"], cv["split"]]).transform("max") > 0]
    st = df[df["split"] == "student_test"].set_index(["model", "variant"])[METRICS]

    L = ["# Label-noise experiment: drop trips 00000002 and 00000033 from training?", "",
         "Generated by `python -m src.label_noise_experiment`. Same 5 GroupKFold folds as every model; in each fold "
         "the model is trained with and without the two noisy-label trips and scored on the same validation trips. "
         "The decision uses CV only; student_test is shown for information.", "",
         "| Model | Metric | CV mean, all trips | CV mean, without noisy | Change | Student test, all | Student test, without noisy |",
         "|---|---|---|---|---|---|---|"]
    decisions = {}
    for name in MODELS:
        for k in METRICS:
            a, b = mean.loc[name, (k, "all_trips")], mean.loc[name, (k, "without_noisy")]
            sa, sb = st.loc[(name, "all_trips"), k], st.loc[(name, "without_noisy"), k]
            if k == "log_loss":
                L.append(f"| {name} | {k} | {a:.4f} | {b:.4f} | {b - a:+.4f} | {sa:.4f} | {sb:.4f} |")
            else:
                L.append(f"| {name} | {k} | {a * 100:.2f}% | {b * 100:.2f}% | {(b - a) * 100:+.2f} pts | "
                         f"{sa * 100:.2f}% | {sb * 100:.2f}% |")
        d_top1 = mean.loc[name, ("top1", "without_noisy")] - mean.loc[name, ("top1", "all_trips")]
        d_ll = mean.loc[name, ("log_loss", "without_noisy")] - mean.loc[name, ("log_loss", "all_trips")]
        decisions[name] = (d_top1, d_ll)
    n_aff = affected[["model", "split"]].drop_duplicates().groupby("model").size().to_dict()
    L += ["", f"Folds where the noisy trips were in training (the only folds where the two variants differ): "
          + ", ".join(f"{m}: {n_aff.get(m, 0)} of 5" for m in MODELS) + ".", ""]
    helps = [m for m, (dt, dl) in decisions.items() if dt > 0.001 and dl <= 0]
    hurts = [m for m, (dt, dl) in decisions.items() if dt < -0.001]
    if len(helps) == len(MODELS):
        verdict = "Dropping the two trips improves CV Top-1 without hurting log loss for every model tested: drop them from training."
    elif hurts:
        verdict = (f"Dropping the two trips lowers CV Top-1 for {', '.join(hurts)}: keep them in training "
                   "(the extra data outweighs the label noise).")
    else:
        verdict = ("The CV difference is within 0.1 Top-1 points or mixed across models: no reliable gain, so keep "
                   "them in training (fewer data-specific decisions, same results).")
    L += [f"**Result:** {verdict}", "", f"Runtime: {time.time() - t0:.0f} s.", ""]
    (OUT_DIR / "label_noise_experiment.md").write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L[4:]))


if __name__ == "__main__":
    main()
